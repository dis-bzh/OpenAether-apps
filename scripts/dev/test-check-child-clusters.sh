#!/usr/bin/env bash
# Mutation tests for scripts/check-child-clusters.py: the real tree must pass,
# and each mutation of a copy must fail with its own message. A checker nobody
# has seen fail proves nothing (the example's HelmRepository v2 sat there for
# weeks). Also renders the example next to the shared helmrepositories, as a
# user following the on-ramp would, and asserts one object per name.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
CHECK=(python3 -I "$ROOT/scripts/check-child-clusters.py")
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
fails=0

fresh() { rm -rf "$WORK/c"; cp -r "$ROOT/apps/clusters" "$WORK/c"; }

expect_fail() { # <label> <message regex> ; runs on $WORK/c
  local out
  if out="$("${CHECK[@]}" "$WORK/c" 2>&1)"; then
    echo "FAIL  $1: the checker passed a broken tree"; fails=$((fails + 1)); return
  fi
  if grep -Eq "$2" <<<"$out"; then echo "ok    $1"
  else echo "FAIL  $1: failed for another reason:"; echo "$out" | sed 's/^/        /'; fails=$((fails + 1)); fi
}

fresh
"${CHECK[@]}" "$WORK/c" >/dev/null && echo "ok    real tree passes" \
  || { echo "FAIL  real tree does not pass"; fails=$((fails + 1)); }

fresh
cat >> "$WORK/c/example-scaleway.yaml.example" <<'Y'
---
apiVersion: source.toolkit.fluxcd.io/v2
kind: HelmRepository
metadata: { name: other, namespace: capi-clusters }
spec: { interval: 24h, url: "https://example.invalid" }
Y
expect_fail "HelmRepository at v2 (not served)" "serve \['v1'"

fresh
cat >> "$WORK/c/example-scaleway.yaml.example" <<'Y'
---
apiVersion: source.toolkit.fluxcd.io/v1
kind: HelmRepository
metadata: { name: cilium, namespace: capi-clusters }
spec: { interval: 24h, url: "https://helm.cilium.io" }
Y
expect_fail "second cilium HelmRepository" "already defined by a shared"

fresh
sed -i '/CHILD_BACKUP_S3_BUCKET/d' "$WORK/c/edge-1.yaml"
expect_fail "workload profile without CHILD_BACKUP_S3_BUCKET" "edge-1-gitops: .*lacks CHILD_BACKUP_S3_BUCKET"

fresh
sed -i '/CHILD_BACKUP_TARGET_URL/d' "$WORK/c/edge-2.yaml"
expect_fail "workload profile without CHILD_BACKUP_TARGET_URL" "lacks CHILD_BACKUP_TARGET_URL"

fresh
sed -i '/CHILD_NAME:/d' "$WORK/c/edge-3.yaml"
expect_fail "no CHILD_NAME" "edge-3.*lacks CHILD_NAME"

fresh
sed -i '0,/name: edge-1-talos-ccm/s//name: ${CLUSTER_NAME}-talos-ccm/' "$WORK/c/edge-1.yaml"
expect_fail "unsubstituted name" "keeps a \\$\\{"

fresh
sed -i 's|CP_REPLICAS: "1"|CP_REPLICAS: "1"\n      SOME_ADDRESS: 8.8.4.4|' "$WORK/c/edge-1.yaml"
expect_fail "public IPv4 literal" "public IPv4 literal 8.8.4.4"

fresh
sed -i 's|s3-<your-bucket>-backups-dev$|s3-realname-backups|' "$WORK/c/edge-1.yaml"
expect_fail "non-placeholder bucket" "is not a <placeholder>"

fresh
sed -i 's/cni: { exclusive: false }/cni: { exclusive: true }/' "$WORK/c/example-scaleway.yaml.example"
expect_fail "example drifts from edge-1 Cilium values" "differ from edge-1.yaml"

# Negative control: a profile with neither cnpg nor storage must not demand backup
# variables, otherwise the profile resolution is a blanket requirement. The
# profile is generated by pick.py into a scratch flux dir (never committed).
fresh
mkdir -p "$WORK/flux"
cp -r "$ROOT/apps/flux/workload" "$WORK/flux/workload"
python3 -I "$ROOT/scripts/pick.py" vault -o "$WORK/flux/bare" >/dev/null
sed -i 's/CHILD_PROFILE: workload/CHILD_PROFILE: bare/; /CHILD_BACKUP_/d' "$WORK/c/edge-1.yaml"
if python3 -I "$ROOT/scripts/check-child-clusters.py" "$WORK/c" "$WORK/flux" >/dev/null 2>&1; then
  echo "ok    profile without cnpg/storage needs no backup vars"
else echo "FAIL  negative control: backup vars demanded without cnpg/storage"; fails=$((fails + 1)); fi

# Render as a user would: example renamed, listed next to the shared sources.
if command -v kubectl >/dev/null; then
  fresh
  rm -f "$WORK"/c/edge-?.yaml
  cp "$WORK/c/example-scaleway.yaml.example" "$WORK/c/child.yaml"
  sed -i 's|^resources:|resources:\n  - child.yaml|' "$WORK/c/kustomization.yaml"
  render="$(kubectl kustomize "$WORK/c")"
  n_cilium="$(grep -c '^  name: cilium$' <<<"$render" || true)"
  n_ccm="$(grep -c '^  name: talos-ccm$' <<<"$render" || true)"
  if [ "$n_cilium" = 1 ] && [ "$n_ccm" = 1 ] && ! grep -q '^  name: .*\${' <<<"$render"; then
    echo "ok    example renders: one cilium and one talos-ccm HelmRepository, no literal \${ in a name"
  else echo "FAIL  render: cilium=$n_cilium talos-ccm=$n_ccm or a literal \${ in a name"; fails=$((fails + 1)); fi
else
  echo "skip  render assertion: kubectl not found"
fi

[ "$fails" -eq 0 ] && echo "all child-cluster check tests passed" || { echo "$fails test(s) failed" >&2; exit 1; }
